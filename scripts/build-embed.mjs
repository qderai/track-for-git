/**
 * The page's files (public/) as one module of strings, src/embed-assets.js, for src/embed.js: an app that mounts
 * Track for Git imports them like code, with no build step and no static files of its own.
 *
 *   npm run build:embed
 *
 * test/embed.test.js fails when src/embed-assets.js is older than public/, so the two always ship together.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TEXT = /\.(html|js|css|svg|json|txt|webmanifest)$/;
// Cloudflare's own header rules for the deployment of its own; an app that mounts the page sends its headers itself.
const SKIP = new Set(["_headers"]);

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/** The module's text: every file of public/, line endings as Git stores them (LF), in a fixed order. */
export function render(dir = join(root, "public")) {
  const entries = [];
  for (const file of walk(dir)) {
    const name = relative(dir, file).split("\\").join("/");
    if (SKIP.has(name)) continue;
    if (!TEXT.test(name)) throw new Error(`public/${name}: only text files can be embedded`);
    entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(file, "utf8").replace(/\r\n/g, "\n"))},`);
  }
  return [
    "// Copyright 2026 Qder AI. Licensed under the Apache License, Version 2.0.",
    "// Generated by `npm run build:embed` from public/: the page's files for src/embed.js. Do not edit by hand;",
    "// test/embed.test.js fails when this is older than public/.",
    "export default {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

export const target = join(root, "src", "embed-assets.js");

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(target, render());
  console.log(`src/embed-assets.js: ${Object.keys((await import(`${pathToFileURL(target).href}?${Date.now()}`)).default).length} files`);
}
